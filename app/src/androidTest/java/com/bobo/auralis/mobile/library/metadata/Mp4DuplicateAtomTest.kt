package com.bobo.auralis.mobile.library.metadata

import android.net.Uri
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import java.io.FileInputStream
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Regression test for the TagLib `MP4::Tag::addItem()` duplicate-atom behaviour.
 *
 * Some taggers store several values of one field in several atoms that share a single name: one
 * `----:com.apple.iTunes:GENRE` atom per genre, or one `©wrt` atom per composer. Upstream TagLib
 * kept only the first such atom and logged "Ignoring duplicate atom", which silently dropped every
 * later value before it could reach the JNI layer. Auralis patches the pinned TagLib so that two
 * duplicate items merge into one string list when both sides are string lists, keeping the order in
 * which the atoms appear in the file.
 *
 * The fixture (`androidTest/assets/mp4/duplicate-mp4-atoms.m4a`) is generated by
 * `tools/make-mp4-duplicate-atom-fixture.py` and contains, in this order:
 *
 * - `----:com.apple.iTunes:GENRE` = "Hyperpop"
 * - `----:com.apple.iTunes:GENRE` = "Electropop"
 * - `----:com.apple.iTunes:MOOD` = "hyperpop; electropop" (a single atom)
 * - `----:com.apple.iTunes:CHOICE` = "Same"
 * - `----:com.apple.iTunes:CHOICE` = "Same"
 * - `©wrt` = "Composer One"
 * - `©wrt` = "Composer Two"
 * - a second, verbatim copy of the base file's `trkn` atom
 *
 * These tests call the JNI layer directly rather than going through [MetadataExtractor], so that a
 * failure can only come from TagLib and the JNI bridge, not from the content resolver.
 */
@RunWith(AndroidJUnit4::class)
class Mp4DuplicateAtomTest {
    private lateinit var fixture: File

    @Before
    fun copyFixtureToCache() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        fixture = File(instrumentation.targetContext.cacheDir, FIXTURE_NAME)
        instrumentation.context.assets.open("mp4/$FIXTURE_NAME").use { input ->
            fixture.outputStream().use { output -> input.copyTo(output) }
        }
        assertTrue("fixture was not copied", fixture.length() > 0)
    }

    /** The bug reported on a real file: only the first of two freeform genre atoms survived. */
    @Test
    fun duplicateFreeformStringAtomsAreMergedInFileOrder() {
        assertEquals(
            listOf("Hyperpop", "Electropop"),
            extract().mp4["----:COM.APPLE.ITUNES:GENRE"],
        )
    }

    /**
     * The same problem applies to standard text atoms, so the fix must not be specific to GENRE.
     * `©wrt` (composer) is what a real Brat release actually repeats.
     */
    @Test
    fun duplicateStandardTextAtomsAreMergedInFileOrder() {
        assertEquals(listOf("Composer One", "Composer Two"), extract().mp4["\u00A9wrt"])
    }

    /** Single-valued atoms must behave exactly as before. */
    @Test
    fun singleValueAtomsAreUnchanged() {
        val mp4 = extract().mp4
        assertEquals(listOf("Auralis Fixture"), mp4["\u00A9nam"])
        assertEquals(listOf("Fixture Artist"), mp4["\u00A9ART"])
        assertEquals(listOf("Fixture Album Artist"), mp4["aART"])
        assertEquals(listOf("Fixture Album"), mp4["\u00A9alb"])
    }

    /** Merging string lists must not split a value that happens to contain a separator. */
    @Test
    fun mergeDoesNotSplitValues() {
        assertEquals(
            listOf("hyperpop; electropop"),
            extract().mp4["----:COM.APPLE.ITUNES:MOOD"],
        )
    }

    /** Merging must not de-duplicate: two identical values are two values. */
    @Test
    fun mergeDoesNotDeduplicate() {
        assertEquals(listOf("Same", "Same"), extract().mp4["----:COM.APPLE.ITUNES:CHOICE"])
    }

    /**
     * Duplicate items that are not string lists (here `trkn`, an integer pair) must keep upstream
     * TagLib behaviour: the first atom wins and the duplicate is ignored.
     */
    @Test
    fun duplicateNonStringListItemsKeepTagLibBehaviour() {
        assertEquals(listOf("5/12"), extract().mp4["trkn"])
    }

    private fun extract(): Metadata {
        val target = MetadataTarget(uri = Uri.fromFile(fixture), fileName = fixture.name)
        val result = FileInputStream(fixture).use { TagLibJNI.open(target, it) }
        val success = result as? MetadataResult.Success
        requireNotNull(success) { "expected Success but got $result" }
        return requireNotNull(success.metadata) { "expected metadata but got null" }
    }

    private companion object {
        const val FIXTURE_NAME = "duplicate-mp4-atoms.m4a"
    }
}
